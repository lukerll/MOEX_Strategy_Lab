"""Типографика текста агента.

Модель пишет как умеет, а мы молча приводим текст к одному виду:
- длинное тире между словами становится дефисом с пробелами, перед числом двоеточием;
- короткое тире в диапазонах («2023–2026») становится дефисом;
- знак числа после слова, которое уже говорит о направлении («убыток −17,38%»), убираем;
- оставшийся минус у числа пишем типографским «−», как в карточках отчёта.
"""
from __future__ import annotations

import re

# Слова, которые сами задают направление: знак после них лишний.
_DIRECTION = r"(?:убыт|потер|просад|сниж|паден|упал|отстав|прибыл|заработ|выигр|рост|вырос|прирост)\w*"

# Тире перед числом (или словами «минус/плюс» перед числом) -> двоеточие.
_DASH_BEFORE_NUM = re.compile(r"(?:\s*—\s*|\s+–\s+)(?=(?:[−\-+]?\d|минус\s|плюс\s))", re.IGNORECASE)
# Остальные длинные тире и «висячие» короткие тире с пробелами -> дефис с пробелами.
_DASH_SPACED = re.compile(r"\s*—\s*|\s+–\s+")
# Короткое тире без пробелов (диапазоны 2023–2026, февраль–июль) -> дефис.
_EN_DASH = re.compile(r"–")
# Слово направления, до 40 символов без цифр и конца фразы, затем знак у числа.
_SIGN_AFTER_WORD = re.compile(rf"(?i)(\b{_DIRECTION}[^.!?\d\n−+\-]{{0,40}}?)[−+\-](?=\d)")
# Одиночный дефис-минус у числа -> «−». Диапазоны и даты (цифра перед дефисом) не трогаем.
_HYPHEN_MINUS = re.compile(r"(?<![\w\d])-(?=\d)")


def tidy_prose(text: str) -> str:
    if not text:
        return text
    out = _DASH_BEFORE_NUM.sub(": ", text)
    out = _DASH_SPACED.sub(" - ", out)
    out = _EN_DASH.sub("-", out)
    out = re.sub(r"(?i)(\b" + _DIRECTION + r")\s*:\s*(?=[−+\-]?\d)", r"\1 ", out)  # «убыток: 25%» -> «убыток 25%»
    out = _SIGN_AFTER_WORD.sub(r"\1", out)
    out = _HYPHEN_MINUS.sub("−", out)
    out = re.sub(r"[ \t]{2,}", " ", out)
    out = re.sub(r"\s+([,.:;])", r"\1", out)
    return out.strip()

def find_terms(text: str) -> list[str]:
    low = (text or "").lower().replace("ё", "е")
    return [k for k, (pat, _, _) in TERMS.items() if re.search(pat, low)]


def detect(text: str) -> str | None:
    """'overview', 'examples' или ключ термина, если реплика это вопрос о словах, а не стратегия."""
    t = (text or "").strip()
    if not t or len(t) > 300:
        return None
    if _EXAMPLE.search(t) and not _STRATEGY.search(t):
        return "examples"
    if not _ASK.search(t) or _STRATEGY.search(t):
        return None
    terms = find_terms(t)
    if _ALL.search(t) or len(terms) > 2:
        return "overview"
    if terms:
        return ",".join(terms)
    return None


